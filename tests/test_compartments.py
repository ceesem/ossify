def test_custom_feature_spec(cell):
    """A custom spec controls feature names, computation, and column order."""
    spec = [
        MappedFeature(
            "area", "area_nm2", map_agg="sum", scale=1.0, neighborhood_agg="sum"
        ),
        CountFeature("n_out", "pre_syn", neighborhood_agg="sum"),
        DerivedFeature(
            "syn_per_area",
            lambda df: df["n_out"] / (df["area"] + 1),
            inputs=["n_out", "area"],
        ),
    ]
    df = make_skel_prop_df(cell, downstream_hops=3, feature_spec=spec)
    # Columns are exactly the spec, base then neighborhood, in spec order.
    assert list(df.columns) == [
        "area",
        "n_out",
        "syn_per_area",
        "down_area",
        "down_n_out",
        "down_syn_per_area",
    ]
    # DerivedFeature is recomputed consistently from neighborhood columns.
    np.testing.assert_allclose(
        df["down_syn_per_area"].to_numpy(),
        (df["down_n_out"] / (df["down_area"] + 1)).to_numpy(),
    )
    # The custom "area" (no unit scale) is the default area_um2 times 1e6.
    ref = make_skel_prop_df(cell, downstream_hops=3)
    np.testing.assert_allclose(df["area"].to_numpy(), ref["area_um2"].to_numpy() * 1e6)


