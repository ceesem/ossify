def test_custom_vertex_model_no_estimator(cell):
    """The SkeletonVertexModel template works for a non-XGBoost subclass."""

    class SynapseRichModel(SkeletonVertexModel):
        # A trivial heuristic model: "axon-like" where there are more outputs
        # than inputs in the downstream neighborhood. No estimator, no xgboost.
        def score(self, features):
            return (features["down_syn_out"] - features["down_syn_in"]).to_numpy()

        def assign(self, cell, scores):
            return scores > 0

    model = SynapseRichModel(downstream_hops=15)
    labels = model.predict(cell)
    assert labels.dtype == bool
    assert labels.shape[0] == cell.skeleton.n_vertices


def test_axon_mask_to_layer(cell, labeler):
    skel_mask = labeler.predict_axon_mask(cell)
    graph_mask = labeler.predict_axon_mask(cell, to_layer="graph")
    assert graph_mask.shape[0] == cell.graph.n_vertices
    assert graph_mask.dtype == bool
    # Mapping to another layer should preserve the rough axon fraction.
    assert abs(graph_mask.mean() - skel_mask.mean()) < 0.1


def test_predict_unaries(cell, labeler):
    from ossify.structured_prediction import TransitionSchema, decode_tree

    u = labeler.predict_unaries(cell)
    n = cell.skeleton.n_vertices
    assert u.shape == (n, 2)
    assert np.all(np.isfinite(u))
    # axon-preference (col1 - col0) is the natural-log odds; predict_vertex_prob_ratio
    # is the same thing in log2, so they agree up to ln(2).
    r = labeler.predict_vertex_prob_ratio(cell)
    np.testing.assert_allclose(u[:, 1] - u[:, 0], r * np.log(2), rtol=1e-6, atol=1e-9)
    # unaries + schema (built from the model's class order) decode without error.
    schema = TransitionSchema(
        classes=list(labeler.classes),
        transitions={("axon", "dendrite"): 10.0},
        root_classes=["dendrite"],
    )
    labels, edge_cost = decode_tree(cell.skeleton, u, schema)
    assert labels.shape == (n,)
    assert edge_cost.shape == (n,)


def test_computed_feature(cell):
    import ossify.compartments as cp

    n = cell.skeleton.n_vertices
    spec = [
        cp.ComputedFeature(
            "dtr", func=lambda c: c.skeleton.distance_to_root(as_positional=True)
        )
    ]
    df = cp.make_skel_prop_df_base(cell, feature_spec=spec)
    assert df.shape == (n, 1)
    np.testing.assert_allclose(
        df["dtr"].to_numpy(), cell.skeleton.distance_to_root(as_positional=True)
    )


def test_computed_feature_gets_neighborhood_aggregation(cell):
    import ossify.compartments as cp

    spec = [
        cp.ComputedFeature(
            "dtr",
            func=lambda c: c.skeleton.distance_to_root(as_positional=True),
            neighborhood_agg="mean",
        )
    ]
    df = cp.make_skel_prop_df(cell, downstream_hops=3, feature_spec=spec)
    assert "dtr" in df.columns and "down_dtr" in df.columns
