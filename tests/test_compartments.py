"""Parity tests for ossify.compartments against the original l2label output.

The reference artifacts in tests/data/l2label_reference/ were generated by
running the original meshparty-based l2label on the v1dd sample meshwork with
the bundled ``v1dd_ds15_us0_bd0`` model. These tests assert the ossify port
reproduces that output.
"""

import pathlib

import numpy as np
import pandas as pd
import pytest

pytest.importorskip("xgboost")
pytest.importorskip("sklearn")
pytest.importorskip("h5py")

import ossify
from ossify.compartments import (
    AxonLabel,
    CountFeature,
    DerivedFeature,
    MappedFeature,
    SkeletonVertexModel,
    get_models,
    load_model_config,
    make_skel_prop_df,
)

DATA = pathlib.Path(__file__).parent / "data"
REF = DATA / "l2label_reference"
MESHWORK = DATA / "v1dd_864691132533489754.h5"
MODEL = "v1dd_ds15_us0_bd0.json"

FEATURE_COLUMNS = [
    "area_um2",
    "vol_um3",
    "max_dt_um",
    "vol_to_area",
    "syn_in",
    "syn_out",
    "down_area_um2",
    "down_vol_um3",
    "down_max_dt_um",
    "down_vol_to_area",
    "down_syn_in",
    "down_syn_out",
]

pytestmark = pytest.mark.skipif(
    not MESHWORK.exists() or not REF.exists(),
    reason="v1dd sample meshwork and/or l2label reference artifacts not present",
)


@pytest.fixture(scope="module")
def cell():
    c, _ = ossify.import_legacy_meshwork(str(MESHWORK), as_pcg_skel=True)
    return c


@pytest.fixture(scope="module")
def labeler():
    return AxonLabel(MODEL)


def test_model_registry():
    assert MODEL in get_models()
    cfg = load_model_config(MODEL)
    assert cfg["downstream_hops"] == 15
    assert cfg["feature_columns"] == FEATURE_COLUMNS
    assert cfg["model_file"].exists()


def test_feature_extraction_parity(cell):
    df = make_skel_prop_df(
        cell, downstream_hops=15, upstream_hops=0, bidirectional_hops=0
    )
    ref = pd.read_pickle(REF / "v1dd_features.pkl")
    assert list(df.columns) == FEATURE_COLUMNS
    for col in FEATURE_COLUMNS:
        np.testing.assert_allclose(
            df[col].to_numpy(dtype=float),
            ref[col].to_numpy(dtype=float),
            rtol=1e-9,
            atol=1e-9,
            err_msg=f"feature column {col} differs from l2label reference",
        )


