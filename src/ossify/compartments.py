"""Machine-learning axon/dendrite compartment labeling for ossify cells.

This is a port of the `l2label` package onto ossify's `Cell`/`SkeletonLayer`
data structures. It extracts per-skeleton-vertex morphological + synaptic
features (optionally aggregated over graph neighborhoods), runs a trained
XGBoost classifier, smooths the per-vertex probabilities along the skeleton,
votes per segment, and restricts the dendrite to the root-connected component.

Requires the optional ``compartments`` extra (``pip install ossify[compartments]``)
for xgboost.

Notes for future generalization (kept intentionally close to l2label for now):
- The feature set and the binary axon/dendrite target are currently hard-coded
  to match the shipped models. Additional compartments (e.g. "primary axon",
  "apical dendrite") would require a multi-class target and richer features.
- The post-ML smoothing uses `algorithms.smooth_features` (global Laplacian
  heat-equation smoothing); the segment-vote + root-component heuristics that
  follow are candidates for replacement.
"""

