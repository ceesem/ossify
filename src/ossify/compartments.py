class ProbaVertexModel(SkeletonVertexModel):
    """Per-vertex probability encoder wrapping any ``predict_proba`` estimator.

    The **encode** stage of the ``encode -> decode -> clean`` pipeline. It owns
    the feature extraction, the fitted classifier, and the optional probability
    smoothing; its :meth:`predict_unaries` output feeds a :class:`StructuredLabeler`
    for the topology-aware decode. Used on its own, :meth:`predict` returns the
    structure-free per-vertex argmax.

    The classifier is **any fitted estimator exposing ``predict_proba``**
    (XGBoost, scikit-learn ``RandomForestClassifier``, a future GNN wrapper, ...);
    nothing here is XGBoost-specific. Its ``classes_`` (when present) define the
    probability column order, which a :class:`StructuredLabeler` validates against
    its schema.

    Parameters
    ----------
    estimator : object
        Fitted classifier with ``predict_proba(X) -> (n, K)``.
    feature_columns : list of str
        Columns of the extracted feature frame to feed the estimator, in the
        order it was trained on.
    downstream_hops, upstream_hops, bidirectional_hops : int
        Neighborhood-aggregation radii for feature extraction (must match how
        the estimator was trained).
    smooth_alpha : float, optional
        If given, Laplacian-smooth the probabilities along the skeleton with this
        alpha. Default ``None`` leaves graph coupling to the decoder's transition
        costs.
    unary_clip : float
        Numerical guard on the per-vertex log-potentials: :meth:`to_unaries`
        clamps each class's unary to ``[-unary_clip, +unary_clip]``, keeping a
        zero probability from becoming ``log(0) = -inf`` (which would poison the
        decode's sums) and bounding magnitudes that float precision makes
        meaningless. It is expressed in the same log-score (nat) units as a
        :class:`~ossify.structured_prediction.TransitionSchema`'s transition
        costs. The default :data:`DEFAULT_UNARY_CLIP` is a deliberately large rail
        -- **comfortably above any transition cost** -- so it never binds on real
        evidence and does not change the labeling; it only tames degenerate
        ``0``/``1`` probabilities. Set *below* a transition cost it stops being a
        pure guard and becomes a confidence cap that can change results (it then
        caps the log-odds between any two classes at ``unary_clip`` -- equivalent
        to flooring probabilities at ``exp(-unary_clip)``); that regime is opt-in.
    feature_spec : list of feature definitions, optional
        See :func:`make_skel_prop_df`. Defaults to :data:`DEFAULT_FEATURE_SPEC`.
    windows : sequence of Window, optional
        Distance- or hop-based neighborhoods to aggregate over, in addition to
        the hop arguments (see :func:`make_skel_prop_df`). Like a custom
        ``feature_spec``, these are not serialized.
    feature_set : str, optional
        Name of an entry in :data:`FEATURE_SETS` (``"distance"`` or
        ``"local"``), which supplies both ``feature_spec`` and ``windows``.
        Unlike passing those two directly, a named set is serialized, so the
        model can be saved with :meth:`to_dict` and loaded from a config that
        has a ``feature_set`` key.

    Examples
    --------
    >>> encoder = ProbaVertexModel(fitted, columns, feature_set="local")
    >>> encoder = ProbaVertexModel.from_config("my_models/unproofread.json")
    """

    #: Bumped when :meth:`to_dict`'s shape changes incompatibly. Independent of
    #: the ossify package version.
    _SCHEMA_VERSION = 1

    def __init__(
        self,
        estimator,
        feature_columns: List[str],
        *,
        downstream_hops: int = 0,
        upstream_hops: int = 0,
        bidirectional_hops: int = 0,
        smooth_alpha: Optional[float] = None,
        unary_clip: float = DEFAULT_UNARY_CLIP,
        feature_spec: Optional[List[FeatureDef]] = None,
        windows: Optional[Sequence[WindowDef]] = None,
        feature_set: Optional[str] = None,
    ):
        if unary_clip is None or unary_clip <= 0.0:
            raise ValueError(
                f"unary_clip must be a positive number; got {unary_clip!r}."
            )
        if feature_set is not None:
            if feature_spec is not None or windows is not None:
                raise ValueError(
                    "Pass either feature_set or feature_spec/windows, not both."
                )
            if feature_set not in FEATURE_SETS:
                raise ValueError(
                    f"Unknown feature_set {feature_set!r}; choose from "
                    f"{sorted(FEATURE_SETS)}."
                )
            feature_spec, windows = FEATURE_SETS[feature_set]
        self._feature_set = feature_set
        self._estimator = estimator
        self._feature_columns = list(feature_columns)
        self._smooth_alpha = smooth_alpha
        self._unary_clip = float(unary_clip)
        #: The ``config`` argument the instance was built from via
        #: :meth:`from_config` (a bundled model name, a user config dict, or a
        #: config file path); ``None`` when built directly from an estimator.
        #: Lets :meth:`to_dict` round-trip without re-serializing the estimator.
        self._config_ref: Optional[Union[dict, str]] = None
        super().__init__(
            downstream_hops=downstream_hops,
            upstream_hops=upstream_hops,
            bidirectional_hops=bidirectional_hops,
            feature_spec=feature_spec,
            windows=windows,
        )

    @staticmethod
    def _resolve_config(config: Optional[Union[dict, str]]) -> dict:
        if isinstance(config, dict):
            return config
        if config is not None:
            path = pathlib.Path(config)
            if path.parent != pathlib.Path("."):
                # A config file of your own: its model_file is read relative to it.
                return load_model_config(path.name, dir=str(path.parent))
        return load_model_config(config, dir=None)

    @classmethod
    def from_config(
        cls,
        config: Optional[Union[dict, str]] = None,
        *,
        smooth_alpha: Optional[float] = None,
        unary_clip: Optional[float] = None,
        feature_spec: Optional[List[FeatureDef]] = None,
    ) -> "ProbaVertexModel":
        """Build from an XGBoost model config.

        ``config`` is the name of a bundled model, the path of a config file
        of your own (its ``model_file`` is read relative to the config), or a
        config dict. Loads the estimator, feature columns, hop settings and,
        if the config has a ``feature_set`` key, that named feature set (see
        :data:`FEATURE_SETS`). ``smooth_alpha`` defaults to
        the config's ``spread_alpha``; ``unary_clip`` to the config's ``unary_clip``
        key, falling back to :data:`DEFAULT_UNARY_CLIP`.
        """
        config_ref = config if config is not None else DEFAULT_MODEL
        resolved = cls._resolve_config(config)
        if smooth_alpha is None:
            smooth_alpha = resolved.get("spread_alpha")
        if unary_clip is None:
            unary_clip = resolved.get("unary_clip", DEFAULT_UNARY_CLIP)
        obj = cls(
            _load_xgboost_classifier(resolved["model_file"]),
            resolved["feature_columns"],
            downstream_hops=resolved.get("downstream_hops", 0),
            upstream_hops=resolved.get("upstream_hops", 0),
            bidirectional_hops=resolved.get("bidirectional_hops", 0),
            smooth_alpha=smooth_alpha,
            unary_clip=unary_clip,
            feature_spec=feature_spec,
            feature_set=resolved.get("feature_set"),
        )
        obj._config_ref = config_ref
        return obj

    def to_dict(self, *, model_file: Optional[Union[str, pathlib.Path]] = None) -> dict:
        """Plain-data representation, round-trippable via :meth:`from_dict`.

        When built via :meth:`from_config`, the ``config`` it was given (a
        bundled model name, config file path, or dict) is stored directly, so
        reloading re-resolves the same estimator without touching it.

        Otherwise (built directly from an ``estimator``), the estimator has no
        known source file: pass ``model_file`` to save it there (requires an
        estimator with a ``save_model(path)`` method, e.g. XGBoost) and a fresh
        config dict pointing at it is built automatically. Without
        ``model_file``, this raises -- there is nothing to persist besides the
        estimator itself, and this is deliberately not a pickle.

        Raises
        ------
        ValueError
            If ``feature_spec`` or ``windows`` were passed directly (they may
            contain callables that cannot be serialized; name them with
            ``feature_set`` instead) or the estimator's source can't be
            determined.
        """
        if self._feature_set is None and (
            self._feature_spec is not None or self._windows is not None
        ):
            raise ValueError(
                "This ProbaVertexModel has a custom feature_spec or windows, "
                "which may contain callables and cannot be serialized. Build it "
                "with feature_set=<a name in FEATURE_SETS> to make it savable, "
                "or rebuild the encoder with them when reloading."
            )
        config_ref = self._config_ref
        if config_ref is None:
            if model_file is None:
                raise ValueError(
                    "This ProbaVertexModel was not built via from_config(...), "
                    "so its estimator has no known source file. Pass "
                    "model_file=<path> to save the fitted estimator there "
                    "(requires an estimator with a save_model(path) method, "
                    "e.g. XGBoost), or save/load the estimator yourself and "
                    "build a config dict for from_dict()."
                )
            if not hasattr(self._estimator, "save_model"):
                raise TypeError(
                    f"estimator of type {type(self._estimator).__name__} has no "
                    "save_model(path) method; save it yourself and pass a "
                    "config dict to from_dict() instead."
                )
            self._estimator.save_model(model_file)
            config_ref = {
                "model_file": str(model_file),
                "feature_columns": self._feature_columns,
                "downstream_hops": self._downstream_hops,
                "upstream_hops": self._upstream_hops,
                "bidirectional_hops": self._bidirectional_hops,
            }
            if self._feature_set is not None:
                config_ref["feature_set"] = self._feature_set
        elif isinstance(config_ref, dict):
            config_ref = {
                k: (str(v) if isinstance(v, pathlib.Path) else v)
                for k, v in config_ref.items()
            }
        return {
            "type": "ProbaVertexModel",
            "version": self._SCHEMA_VERSION,
            "ossify_version": _ossify_version(),
            "config": config_ref,
            "smooth_alpha": self._smooth_alpha,
            "unary_clip": self._unary_clip,
        }

    @classmethod
    def from_dict(
        cls,
        d: dict,
        *,
        feature_spec: Optional[List[FeatureDef]] = None,
    ) -> "ProbaVertexModel":
        """Reconstruct a :class:`ProbaVertexModel` from :meth:`to_dict` output.

        Unlike :meth:`from_config`, ``smooth_alpha``/``unary_clip`` are taken
        as-is from ``d`` (not re-defaulted from the config file), so a
        deliberate ``smooth_alpha: null`` (no smoothing) round-trips correctly.
        """
        version = d.get("version", 1)
        if version > cls._SCHEMA_VERSION:
            raise ValueError(
                f"ProbaVertexModel dict has schema version {version}, newer "
                f"than the {cls._SCHEMA_VERSION} this ossify release supports; "
                "upgrade ossify to load it."
            )
        resolved = cls._resolve_config(d["config"])
        obj = cls(
            _load_xgboost_classifier(resolved["model_file"]),
            resolved["feature_columns"],
            downstream_hops=resolved.get("downstream_hops", 0),
            upstream_hops=resolved.get("upstream_hops", 0),
            bidirectional_hops=resolved.get("bidirectional_hops", 0),
            smooth_alpha=d.get("smooth_alpha"),
            unary_clip=d.get("unary_clip", DEFAULT_UNARY_CLIP),
            feature_spec=feature_spec,
            feature_set=resolved.get("feature_set"),
        )
        obj._config_ref = d["config"]
        return obj

    @property
    def estimator(self):
        return self._estimator

    @property
    def feature_columns(self) -> list:
        return list(self._feature_columns)

    @property
    def classes_(self):
        """The estimator's class order, if it exposes ``classes_`` (else None)."""
        c = getattr(self._estimator, "classes_", None)
        return None if c is None else list(c)

    # --- SkeletonVertexModel hooks -----------------------------------------

    def score(self, features: pd.DataFrame) -> np.ndarray:
        """Per-vertex class probabilities ``(n_vertices, K)`` from the estimator."""
        return self._estimator.predict_proba(features[self._feature_columns].to_numpy())

    def smooth(self, cell: Cell, scores: np.ndarray) -> np.ndarray:
        """Optional Laplacian smoothing of probabilities; identity if no alpha."""
        if self._smooth_alpha is None:
            return scores
        return smooth_features(
            cell.skeleton, scores.astype(float), alpha=self._smooth_alpha
        )

    def to_unaries(self, scores: np.ndarray) -> np.ndarray:
        """Log-potentials from probabilities, clamped to ``+/- unary_clip``.

        Primarily a numerical guard: ``log(p)`` sends a zero probability to
        ``-inf``, which poisons the decode's sums, and float limits make very
        large magnitudes meaningless anyway. ``unary_clip`` bounds the result to a
        finite range; at the default :data:`DEFAULT_UNARY_CLIP` it never binds on
        real evidence and so does not change the labeling. See ``unary_clip`` in
        the class docstring.
        """
        floor = float(np.exp(-self._unary_clip))
        clipped = np.clip(np.asarray(scores, dtype=float), floor, None)
        return np.clip(np.log(clipped), -self._unary_clip, self._unary_clip)


# --- Structured compartment labeler -----------------------------------------

#: Registry of encoder types :class:`StructuredLabeler` can (de)serialize.
#: Extend when a new :class:`SkeletonVertexModel` subclass grows a
#: to_dict/from_dict pair.
_ENCODER_TYPES = {"ProbaVertexModel": ProbaVertexModel}


class StructuredLabeler:
    """Compose an encoder + transition priors into a tree-decoded labeler.

    The **decode -> clean** seat of the ``encode -> decode -> clean`` pipeline,
    and the principled successor to :class:`AxonLabel`'s segment-vote/root-component
    heuristic. It pulls per-vertex unaries from any :class:`SkeletonVertexModel`
    encoder (:meth:`~SkeletonVertexModel.predict_unaries`), applies the
    :class:`~ossify.structured_prediction.TransitionSchema` priors via an exact
    tree-MAP :func:`~ossify.structured_prediction.decode_tree`, and optionally
    runs :func:`~ossify.structured_prediction.absorb_small_compartments` to clean
    up short, noise-driven label flips.

    Keeping the encoder a separate object is the point: ossify owns the priors and
    the exact inference, the encoder owns features->probabilities, and either side
    can be swapped (a tabular classifier today, a GNN later) without touching the
    other. The decode/schema/absorb stack is fully K-class, so multi-compartment
    targets (soma / basal / apical / axon) need only a richer estimator and schema.

    Parameters
    ----------
    encoder : SkeletonVertexModel
        Produces ``(n_vertices, K)`` unaries via ``predict_unaries`` -- typically
        a :class:`ProbaVertexModel`, but any subclass works.
    schema : TransitionSchema
        Declares the class names, transition priors, and ``default_cost``. There
        is intentionally no default: a new estimator must declare its own priors.
        ``schema.classes`` must match the encoder's class order (validated when
        the encoder exposes ``classes_``).
    absorb_min_size : int, optional
        Absorb decoded compartments with this many vertices or fewer.
    absorb_min_weight : float, optional
        Absorb decoded compartments whose cable length (``half_edge_length``) is
        this or less.
    """

    #: Bumped when :meth:`to_dict`'s shape changes incompatibly. Independent of
    #: the ossify package version.
    _SCHEMA_VERSION = 1

    def __init__(
        self,
        encoder: SkeletonVertexModel,
        schema: TransitionSchema,
        *,
        absorb_min_size: Optional[int] = None,
        absorb_min_weight: Optional[float] = None,
    ):
        self._encoder = encoder
        self._schema = schema
        self._absorb_min_size = absorb_min_size
        self._absorb_min_weight = absorb_min_weight
        self._validate_classes()

    def _validate_classes(self) -> None:
        """Check schema.classes lines up with the encoder's class order.

        When the encoder exposes ``classes_`` (e.g. a :class:`ProbaVertexModel`
        over a fitted estimator), the column count and order are checked: a
        ``range(K)`` / ``[False, True]`` placeholder just supplies the count and
        the schema names the classes; meaningful labels must match in order. An
        encoder without ``classes_`` is validated against the unary width at
        decode time.
        """
        est_classes = getattr(self._encoder, "classes_", None)
        if est_classes is None:
            return  # validated against unary width in _decode()
        est_classes = list(est_classes)
        K = len(est_classes)
        if len(self._schema.classes) != K:
            raise ValueError(
                f"schema has {len(self._schema.classes)} classes but the "
                f"encoder predicts {K}."
            )
        if est_classes != list(range(K)) and est_classes != list(self._schema.classes):
            raise ValueError(
                f"encoder.classes_={est_classes} must match schema.classes="
                f"{list(self._schema.classes)} in order; these define the "
                "probability/unary column order."
            )

    @property
    def encoder(self) -> SkeletonVertexModel:
        return self._encoder

    @property
    def classes(self) -> tuple:
        """Class labels, in unary/probability column order (from the schema)."""
        return tuple(self._schema.classes)

    @property
    def schema(self) -> TransitionSchema:
        return self._schema

    def predict_unaries(self, cell: Cell) -> np.ndarray:
        """The encoder's ``(n_vertices, K)`` log-potentials for this cell."""
        return self._encoder.predict_unaries(cell)

    def _decode(self, cell: Cell):
        """Decode the encoder's unaries to labels + per-edge violation costs."""
        unaries = self._encoder.predict_unaries(cell)
        if unaries.shape[1] != len(self._schema.classes):
            raise ValueError(
                f"encoder produced {unaries.shape[1]} unary columns but schema "
                f"has {len(self._schema.classes)} classes."
            )
        labels, edge_cost = decode_tree(
            cell.skeleton, unaries, self._schema, return_labels_as="index"
        )
        if self._absorb_min_size is not None or self._absorb_min_weight is not None:
            labels = absorb_small_compartments(
                cell.skeleton,
                labels,
                min_size=self._absorb_min_size,
                min_weight=self._absorb_min_weight,
            )
        return labels, edge_cost

    def _as_labels(self, indices: np.ndarray, return_labels_as: str) -> np.ndarray:
        if return_labels_as == "index":
            return indices
        if return_labels_as == "label":
            return np.array(self._schema.classes, dtype=object)[indices]
        raise ValueError("return_labels_as must be 'index' or 'label'.")

    def predict(self, cell: Cell, return_labels_as: str = "label") -> np.ndarray:
        """Per-vertex compartment labels via decode (+absorb).

        ``return_labels_as`` is ``"label"`` (schema class labels, default) or
        ``"index"`` (class indices).
        """
        labels, _ = self._decode(cell)
        return self._as_labels(labels, return_labels_as)

    def predict_with_violations(self, cell: Cell, return_labels_as: str = "label"):
        """Labels plus the per-edge transition cost paid to the parent.

        Returns ``(labels, edge_cost)``; nonzero ``edge_cost`` entries are the
        decoder's transition violations (a morphology QC signal). Costs are from
        the decode, before any small-compartment absorption.
        """
        labels, edge_cost = self._decode(cell)
        return self._as_labels(labels, return_labels_as), edge_cost

    # --- Serialization -------------------------------------------------------

    def to_dict(self, *, model_file: Optional[Union[str, pathlib.Path]] = None) -> dict:
        """Plain-data representation, round-trippable via :meth:`from_dict`.

        Composes :meth:`TransitionSchema.to_dict` and the encoder's own
        ``to_dict`` -- so a labeler built from a bundled model config (the
        common case) serializes down to a small JSON-safe dict with no model
        weights inlined. ``model_file`` is forwarded to the encoder's
        ``to_dict`` for the case where its estimator has no known source file
        (see :meth:`ProbaVertexModel.to_dict`). Includes a ``version`` (this
        dict shape, bumped on breaking changes) and ``ossify_version`` (the
        release that wrote it, for provenance/debugging).
        """
        encoder_type = type(self._encoder).__name__
        if encoder_type not in _ENCODER_TYPES:
            raise TypeError(
                f"Serialization is not supported for encoder type "
                f"{encoder_type!r}; supported types: {sorted(_ENCODER_TYPES)}."
            )
        return {
            "type": "StructuredLabeler",
            "version": self._SCHEMA_VERSION,
            "ossify_version": _ossify_version(),
            "schema": self._schema.to_dict(),
            "encoder": self._encoder.to_dict(model_file=model_file),
            "absorb_min_size": self._absorb_min_size,
            "absorb_min_weight": self._absorb_min_weight,
        }

    @classmethod
    def from_dict(
        cls,
        d: dict,
        *,
        feature_spec: Optional[List[FeatureDef]] = None,
    ) -> "StructuredLabeler":
        """Reconstruct a :class:`StructuredLabeler` from :meth:`to_dict` output.

        ``feature_spec`` is forwarded to the encoder's ``from_dict`` and only
        needed when the original encoder was built with a non-default
        ``feature_spec`` (see :meth:`ProbaVertexModel.to_dict`).
        """
        version = d.get("version", 1)
        if version > cls._SCHEMA_VERSION:
            raise ValueError(
                f"StructuredLabeler dict has schema version {version}, newer "
                f"than the {cls._SCHEMA_VERSION} this ossify release supports; "
                "upgrade ossify to load it."
            )
        encoder_dict = d["encoder"]
        encoder_type = encoder_dict.get("type")
        encoder_cls = _ENCODER_TYPES.get(encoder_type)
        if encoder_cls is None:
            raise ValueError(
                f"Unknown or unsupported encoder type: {encoder_type!r}; "
                f"supported types: {sorted(_ENCODER_TYPES)}."
            )
        encoder = encoder_cls.from_dict(encoder_dict, feature_spec=feature_spec)
        schema = TransitionSchema.from_dict(d["schema"])
        return cls(
            encoder,
            schema,
            absorb_min_size=d.get("absorb_min_size"),
            absorb_min_weight=d.get("absorb_min_weight"),
        )

    def save_config(
        self,
        filename: Union[str, pathlib.Path],
        *,
        model_file: Optional[Union[str, pathlib.Path]] = None,
    ) -> None:
        """Write :meth:`to_dict` to ``filename`` as JSON."""
        with open(filename, "wb") as f:
            f.write(
                orjson.dumps(
                    self.to_dict(model_file=model_file), option=orjson.OPT_INDENT_2
                )
            )

    @classmethod
    def load_config(
        cls,
        filename: Union[str, pathlib.Path],
        *,
        feature_spec: Optional[List[FeatureDef]] = None,
    ) -> "StructuredLabeler":
        """Load a :class:`StructuredLabeler` from a JSON file written by :meth:`save_config`."""
        with open(filename, "rb") as f:
            d = orjson.loads(f.read())
        return cls.from_dict(d, feature_spec=feature_spec)


# --- One-stop loader --------------------------------------------------------


def describe_models(dir: Optional[str] = None) -> pd.DataFrame:
    """The bundled models, one row each: what they were trained on and what they are for.

    Returns
    -------
    pd.DataFrame
        Indexed by model name (the name :func:`load_labeler` and
        :meth:`ProbaVertexModel.from_config` take), with ``dataset``,
        ``feature_set``, ``has_decode`` and ``description`` columns.

    Examples
    --------
    >>> describe_models()[["dataset", "description"]]
    """
    rows = []
    for filename in sorted(get_models(dir)):
        config = load_model_config(filename, dir=dir)
        rows.append(
            {
                "model": pathlib.Path(filename).stem,
                "dataset": config.get("dataset"),
                "feature_set": config.get("feature_set", "hops"),
                "has_decode": "decode" in config,
                "description": config.get("description", ""),
            }
        )
    return pd.DataFrame(rows).set_index("model")


def load_labeler(
    model: str,
    *,
    schema: Optional[TransitionSchema] = None,
    absorb_min_size: Union[int, None, Literal["config"]] = "config",
) -> "StructuredLabeler":
    """Load a ready-to-use compartment labeler from a model's config.

    Loads the model and wraps it in a :class:`StructuredLabeler` with the
    decode settings stored in the model's config, so the result labels a cell
    in one call. The config's ``decode`` block holds the transition costs (a
    :meth:`TransitionSchema.to_dict`) and ``absorb_min_size``: the values the
    model was evaluated with.

    Parameters
    ----------
    model : str
        Name of a bundled model, such as ``"v1dd_distance"`` or
        ``"minnie65_local"`` (see :func:`describe_models`), or the path of a
        config file of your own.
    schema : TransitionSchema, optional
        Transition costs for the decode, in place of the config's.
    absorb_min_size : int or None, optional
        Decoded compartments of this many vertices or fewer are absorbed into
        their parent; None skips the step. Defaults to the config's value.

    Returns
    -------
    StructuredLabeler
        Call ``.predict(cell)`` for per-vertex labels.

    Raises
    ------
    ValueError
        If the config has no ``decode`` block and no ``schema`` was given.

    Examples
    --------
    >>> labeler = load_labeler("v1dd_distance")        # proofread v1dd cells
    >>> labels = labeler.predict(cell)
    >>> merged = load_labeler("minnie65_local")        # objects that may hold merges
    """
    decode = ProbaVertexModel._resolve_config(model).get("decode", {})
    if schema is None:
        if "schema" not in decode:
            raise ValueError(
                f"The config of {model!r} has no decode schema; pass schema=."
            )
        schema = TransitionSchema.from_dict(decode["schema"])
    if absorb_min_size == "config":
        absorb_min_size = decode.get("absorb_min_size")
    return StructuredLabeler(
        ProbaVertexModel.from_config(model), schema, absorb_min_size=absorb_min_size
    )
